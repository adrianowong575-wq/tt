const screens = [...document.querySelectorAll('.screen')];
const music = document.getElementById('bgMusic');
let musicStarted = false;

function startMusic() {
  if (musicStarted) return;
  music.play().then(() => { musicStarted = true; }).catch(() => {});
}

document.addEventListener('click', startMusic, { passive: true });
document.addEventListener('touchstart', startMusic, { passive: true });

function showScreen(id, updateHash = true) {
  screens.forEach(screen => screen.classList.toggle('active', screen.id === id));
  window.scrollTo({ top: 0, behavior: 'instant' });
  if (updateHash) history.pushState({ screen: id }, '', id === 'inicio' ? './' : `#${id}`);
}

function openDetail(id, updateHash = true) {
  const item = ITEMS.find(x => x.id === Number(id));
  if (!item) return showScreen('cosas', updateHash);
  document.getElementById('detailNumber').textContent = `${String(item.id).padStart(2, '0')} / 50`;
  const image = document.getElementById('detailImage');
  image.src = item.imagen;
  image.alt = `Imagen de ${item.titulo}`;
  image.onerror = () => { image.onerror = null; image.src = 'images/placeholder.svg'; };
  document.getElementById('detailEmoji').textContent = item.emoji;
  document.getElementById('detailTitle').textContent = item.titulo;
  document.getElementById('detailText').textContent = item.texto;
  screens.forEach(screen => screen.classList.toggle('active', screen.id === 'detalle'));
  window.scrollTo({ top: 0, behavior: 'instant' });
  if (updateHash) history.pushState({ screen: 'detalle', id: item.id }, '', `#cosa-${item.id}`);
}

function renderButtons() {
  const grid = document.getElementById('buttonsGrid');
  grid.innerHTML = ITEMS.map(item => `
    <button class="thing-button" data-id="${item.id}">
      <span class="number">${String(item.id).padStart(2, '0')}</span>
      <span class="emoji">${item.emoji}</span>
      <span class="button-title">${item.titulo}</span>
      <span class="arrow">›</span>
    </button>`).join('');

  grid.addEventListener('click', event => {
    const button = event.target.closest('.thing-button');
    if (button) openDetail(button.dataset.id);
  });
}

document.addEventListener('click', event => {
  const control = event.target.closest('[data-go]');
  if (control) showScreen(control.dataset.go);
});

function routeFromHash() {
  const hash = location.hash.replace('#', '');
  if (hash.startsWith('cosa-')) return openDetail(hash.split('-')[1], false);
  if (['perdon', 'cosas'].includes(hash)) return showScreen(hash, false);
  showScreen('inicio', false);
}

window.addEventListener('popstate', routeFromHash);
renderButtons();
routeFromHash();
